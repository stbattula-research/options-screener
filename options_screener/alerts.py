"""Alerting: email + webhook notifications on new qualifying signals (v3).

Design rules, kept deliberately conservative:

- Alerts fire only for *new* qualifying signals (dedupe against a local
  state file, keyed on ticker+expiry+strike). A re-run of the same day does
  not re-fire.
- Credentials NEVER live in config.yaml. SMTP password, webhook URL and
  addresses come from environment variables only, and are never logged.
- A failing channel must not kill the run: errors are returned in the
  result dict and printed, not raised.
- Alerts are announcements of *research candidates* — the disclaimer goes
  out in every alert body.

Credentials via env:
    ALERT_EMAIL_TO / ALERT_EMAIL_FROM
    ALERT_SMTP_HOST / ALERT_SMTP_PORT (default 587) / ALERT_SMTP_USER
    ALERT_SMTP_PASSWORD
    ALERT_WEBHOOK_URL
"""

import json
import os
import smtplib
import urllib.request
from datetime import date
from email.message import EmailMessage

from .report import DISCLAIMER

STATE_FILENAME = "alerts.json"


def signal_key(sig: dict) -> str:
    return f"{sig['ticker']}|{sig['expiry']}|{sig['strike']}"


def spread_key(sp: dict) -> str:
    return (f"{sp['ticker']}|{sp['expiry']}|"
            f"{sp['short_strike']}/{sp['long_strike']}")


def evaluate(payload: dict, rules: dict) -> list:
    """Return alert items for signals/spreads that meet the rule thresholds.

    Each item: {"kind", "key", "ticker", "reason", "detail"}.
    A signal can produce at most one item (reasons combined).
    """
    min_yield = rules.get("min_annualized_yield", 0.0)
    min_roi = rules.get("min_spread_roi", 0.0)
    min_iv = rules.get("min_iv_rank_true", 2.0)  # >1 disables the IV rule

    items = []
    for s in payload.get("signals", []):
        reasons = []
        ann = s.get("annualized_yield")
        if ann is not None and ann >= min_yield:
            reasons.append(f"annualized yield {ann:.1%} >= {min_yield:.1%}")
        true_rank = s.get("iv_rank_true")
        if true_rank is not None and true_rank >= min_iv:
            reasons.append(f"true IV rank {true_rank:.2f} >= {min_iv:.2f} "
                           f"({s.get('iv_rank_obs', 0)} observations)")
        if reasons:
            items.append({
                "kind": "csp",
                "key": signal_key(s),
                "ticker": s["ticker"],
                "reason": "; ".join(reasons),
                "detail": (f"${s['strike']:.2f} put exp {s['expiry']} "
                           f"({s['dte']} DTE), Δ {s['delta']:.2f}, "
                           f"premium {s['premium_pct']:.2%}, "
                           f"breakeven ${s['breakeven']:.2f}"),
            })
    for sp in payload.get("spreads", []):
        roi = sp.get("roi")
        if roi is not None and roi >= min_roi:
            items.append({
                "kind": "spread",
                "key": spread_key(sp),
                "ticker": sp["ticker"],
                "reason": f"return on risk {roi:.1%} >= {min_roi:.1%}",
                "detail": (f"bull put ${sp['short_strike']:.2f}/"
                           f"${sp['long_strike']:.2f} exp {sp['expiry']}, "
                           f"credit ${sp['net_credit']:.2f}, max loss "
                           f"${sp['max_loss']:.2f}, breakeven "
                           f"${sp['breakeven']:.2f}"),
            })
    return items


def load_state(history_dir: str) -> dict:
    """Load the alert-fired state; tolerate missing or corrupt files."""
    path = os.path.join(history_dir, STATE_FILENAME)
    try:
        with open(path) as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_state(history_dir: str, state: dict) -> None:
    os.makedirs(history_dir, exist_ok=True)
    path = os.path.join(history_dir, STATE_FILENAME)
    with open(path, "w") as f:
        json.dump(state, f, indent=2)


def dedupe(items: list, state: dict) -> list:
    """Keep only items not already alerted. Returns (new_items, state)."""
    seen = set(state.get("fired_keys", []))
    return [it for it in items if it["key"] not in seen]


def render_email_subject(as_of: str, items: list) -> str:
    tickers = sorted({it["ticker"] for it in items})
    return (f"[options-screener] {len(items)} new signal alert(s) "
            f"({as_of}): {', '.join(tickers)}")


def render_email_body(as_of: str, items: list) -> str:
    lines = [f"Options screener alerts — {as_of}", ""]
    for it in items:
        lines.append(f"- [{it['kind'].upper()}] {it['ticker']}: {it['reason']}")
        lines.append(f"  {it['detail']}")
    lines += ["", DISCLAIMER, "",
              "Generated by options-screener (research only)."]
    return "\n".join(lines)


def render_webhook_payload(as_of: str, items: list) -> dict:
    return {
        "text": render_email_body(as_of, items),
        "as_of": as_of,
        "alerts": [{"kind": it["kind"], "ticker": it["ticker"],
                    "reason": it["reason"], "detail": it["detail"]}
                   for it in items],
    }


def _env(name: str, default: str = "") -> str:
    return os.environ.get(name, default).strip()


def send_email(subject: str, body: str) -> None:
    """Send via SMTP. All credentials come from env; raises RuntimeError on
    missing config so the caller can report a clean failure."""
    host = _env("ALERT_SMTP_HOST")
    to = _env("ALERT_EMAIL_TO")
    user = _env("ALERT_SMTP_USER")
    password = os.environ.get("ALERT_SMTP_PASSWORD", "")
    if not host or not to or not user or not password:
        raise RuntimeError(
            "email alerts misconfigured: need ALERT_SMTP_HOST, "
            "ALERT_EMAIL_TO, ALERT_SMTP_USER and ALERT_SMTP_PASSWORD")
    port = int(_env("ALERT_SMTP_PORT", "587") or "587")
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = _env("ALERT_EMAIL_FROM") or user
    msg["To"] = to
    msg.set_content(body)

    # Never log or include credential values anywhere.
    with smtplib.SMTP(host, port, timeout=20) as smtp:
        smtp.starttls()
        smtp.login(user, password)
        smtp.send_message(msg)


def send_webhook(url: str, payload: dict) -> None:
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url, data=data, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=20) as resp:
        if resp.status >= 400:
            raise RuntimeError(f"webhook returned HTTP {resp.status}")


def run_alerts(payload: dict, cfg: dict, dry_run: bool = False) -> dict:
    """Evaluate rules, dedupe, send on enabled channels, persist state.

    Returns {"fired": [...], "would_fire": [...], "channel_errors": {...},
             "channels": [...]}. dry_run prints/evaluates without sending or
    persisting state.
    """
    acfg = cfg.get("alerts", {}) or {}
    rules = acfg.get("rules", {}) or {}
    as_of = payload.get("as_of") or date.today().isoformat()

    state_dir = acfg.get("state_dir", "alert_state")
    state = load_state(state_dir)

    candidates = evaluate(payload, rules)
    new_items = dedupe(candidates, state)

    result = {"fired": [], "would_fire": [], "channel_errors": {},
              "channels": []}

    if not new_items:
        return result
    if dry_run:
        result["would_fire"] = new_items
        return result

    subject = render_email_subject(as_of, new_items)
    body = render_email_body(as_of, new_items)

    email_cfg = acfg.get("email", {}) or {}
    if email_cfg.get("enabled", False):
        result["channels"].append("email")
        try:
            send_email(subject, body)
            result["fired"].extend(new_items)
        except Exception as exc:  # channel failure must not kill the run
            result["channel_errors"]["email"] = str(exc)

    webhook_cfg = acfg.get("webhook", {}) or {}
    webhook_url = _env("ALERT_WEBHOOK_URL")
    if webhook_cfg.get("enabled", False):
        result["channels"].append("webhook")
        if not webhook_url:
            result["channel_errors"]["webhook"] = (
                "webhook enabled but ALERT_WEBHOOK_URL is not set")
        else:
            try:
                send_webhook(webhook_url, render_webhook_payload(as_of, new_items))
                for it in new_items:
                    if it not in result["fired"]:
                        result["fired"].append(it)
            except Exception as exc:
                result["channel_errors"]["webhook"] = str(exc)

    # Only mark items as fired when at least one channel delivered them.
    if result["fired"]:
        seen = set(state.get("fired_keys", []))
        seen.update(it["key"] for it in result["fired"])
        state["fired_keys"] = sorted(seen)
        state["last_run"] = as_of
        save_state(state_dir, state)
    return result
